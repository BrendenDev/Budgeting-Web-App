'use client';

import { useState } from 'react';
import { useUser } from '@/lib/auth-context';
import { useDialog } from '@/components/ConfirmDialog';
import CategoryPicker from '@/components/CategoryPicker';
import AuthGuard from '@/components/AuthGuard';
import Sidebar from '@/components/Sidebar';
import Modal from '@/components/Modal';
import { formatCurrency, formatDate } from '@/lib/calculation-engine';
import { getTodayMT, toDateStringMT } from '@/lib/date-utils';
import { EXPENSE_CATEGORIES, INCOME_CATEGORIES, RULE_FREQUENCIES } from '@/models/schemas';
import { useCachedFetch } from '@/lib/use-cached-fetch';
import { invalidateCache } from '@/lib/data-cache';
import { Page, Section, Button, TextButton, Input, Select, Field, Table, Th, Td, rowClass, Tag, Skeleton, Empty } from '@/components/ui';

function RecurringContent() {
  const { user } = useUser();
  const { confirm, alert: showAlert } = useDialog();
  const [showModal, setShowModal] = useState(false);
  const [editingRule, setEditingRule] = useState(null);
  const [form, setForm] = useState({
    name: '', amount: '', type: 'expense', category: 'Misc',
    frequency: 'monthly', startDate: getTodayMT(),
    endDate: '', accountId: '', description: '', isActive: true,
  });
  const [saving, setSaving] = useState(false);

  // Occurrence detail modal state
  const [showOccurrences, setShowOccurrences] = useState(false);
  const [occRule, setOccRule] = useState(null);
  const [occurrences, setOccurrences] = useState([]);
  const [occSummary, setOccSummary] = useState({ total: 0, active: 0, missing: 0 });
  const [occLoading, setOccLoading] = useState(false);
  const [reinstating, setReinstating] = useState(null);

  const rulesUrl = user?.id ? `/api/recurring?userId=${user.id}` : null;
  const accountsUrl = user?.id ? `/api/accounts?userId=${user.id}` : null;
  const { data: rules, loading: rulesLoading, refresh: refreshRules } = useCachedFetch(rulesUrl, { ttl: 60000 });
  const { data: accounts, loading: accLoading, refresh: refreshAccounts } = useCachedFetch(accountsUrl, { ttl: 60000 });
  const loading = rulesLoading || accLoading;

  const openCreate = () => {
    setEditingRule(null);
    setForm({
      name: '', amount: '', type: 'expense', category: 'Misc',
      frequency: 'monthly', startDate: getTodayMT(),
      endDate: '', accountId: accounts[0]?._id || '', description: '', isActive: true,
    });
    setShowModal(true);
  };

  const openEdit = (rule) => {
    setEditingRule(rule);
    setForm({
      name: rule.name, amount: String(rule.amount), type: rule.type,
      category: rule.category, frequency: rule.frequency,
      startDate: toDateStringMT(rule.startDate),
      endDate: rule.endDate ? toDateStringMT(rule.endDate) : '',
      accountId: rule.accountId || '', description: rule.description || '', isActive: rule.isActive,
    });
    setShowModal(true);
  };

  const handleSave = async (e) => {
    e.preventDefault();
    setSaving(true);
    try {
      const payload = { ...form, amount: Math.abs(Number(form.amount)), userId: user.id, today: getTodayMT() };
      if (editingRule) {
        await fetch(`/api/recurring/${editingRule._id}`, {
          method: 'PUT', headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(payload),
        });
      } else {
        await fetch('/api/recurring', {
          method: 'POST', headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(payload),
        });
      }
      // Immediately process rules to materialize any past occurrences
      await fetch('/api/recurring/process', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ userId: user.id, today: getTodayMT() }),
      });
      setShowModal(false);
      invalidateCache('/api/recurring');
      invalidateCache('/api/transactions');
      invalidateCache('/api/accounts');
      refreshRules();
    } catch (e) { console.error(e); }
    setSaving(false);
  };

  const handleDelete = async (rule) => {
    const ok = await confirm(`Are you sure you want to delete "${rule.name}"?`, {
      title: 'Delete Recurring Item',
      confirmText: 'Delete Recurring Item',
      variant: 'danger',
      details: [
        'All auto-generated transactions will be deleted',
        'Account balances will be reversed',
        'This action cannot be undone',
      ],
    });
    if (!ok) return;
    await fetch(`/api/recurring/${rule._id}`, { method: 'DELETE' });
    invalidateCache('/api/recurring');
    invalidateCache('/api/transactions');
    invalidateCache('/api/accounts');
    refreshRules();
  };

  const handleUndo = async (rule) => {
    const ok = await confirm(`Undo all transactions generated by "${rule.name}"?`, {
      title: 'Undo Recurring Transactions',
      confirmText: 'Undo All',
      variant: 'warning',
      details: [
        'All auto-generated transactions for this rule will be deleted',
        'Account balance changes will be reversed',
        'The occurrence tracker will be reset',
        'The rule itself will remain active',
      ],
    });
    if (!ok) return;
    try {
      const res = await fetch(`/api/recurring/${rule._id}/undo`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ deleteRule: false }),
      });
      const result = await res.json();
      if (res.ok) {
        await showAlert(`Undone ${result.undoneCount} transaction${result.undoneCount !== 1 ? 's' : ''}. Account balances have been reversed.`, {
          title: 'Undo Complete',
          variant: 'success',
          confirmText: 'Got it',
        });
      } else {
        await showAlert(result.error || 'Something went wrong', {
          title: 'Undo Failed',
          variant: 'danger',
        });
      }
    } catch (e) {
      await showAlert('Network error — could not reach the server.', {
        title: 'Undo Failed',
        variant: 'danger',
      });
    }
    invalidateCache('/api/recurring');
    invalidateCache('/api/transactions');
    invalidateCache('/api/accounts');
    refreshRules();
  };

  const toggleActive = async (rule) => {
    await fetch(`/api/recurring/${rule._id}`, {
      method: 'PUT', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ isActive: !rule.isActive }),
    });
    invalidateCache('/api/recurring');
    refreshRules();
  };

  const categories = form.type === 'income' ? INCOME_CATEGORIES : EXPENSE_CATEGORIES;
  const getAccountName = (id) => accounts.find(a => a._id === id)?.name || '—';
  const freqLabel = { daily: 'Daily', weekly: 'Weekly', biweekly: 'Bi-weekly', monthly: 'Monthly', quarterly: 'Quarterly', yearly: 'Yearly' };

  // ─── Occurrence Detail Handlers ─────────────────
  const openOccurrences = async (rule) => {
    setOccRule(rule);
    setShowOccurrences(true);
    setOccLoading(true);
    try {
      const res = await fetch(`/api/recurring/${rule._id}/occurrences?userId=${user.id}&today=${getTodayMT()}`);
      const data = await res.json();
      setOccurrences(data.occurrences || []);
      setOccSummary(data.summary || { total: 0, active: 0, missing: 0 });
    } catch (e) {
      console.error(e);
      setOccurrences([]);
    }
    setOccLoading(false);
  };

  const handleReinstate = async (occ) => {
    setReinstating(occ.date);
    try {
      const res = await fetch(`/api/recurring/${occRule._id}/occurrences`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ date: occ.date, userId: user.id }),
      });
      if (res.ok) {
        // Refresh the occurrences list
        await openOccurrences(occRule);
      } else {
        const err = await res.json();
        await showAlert(err.error || 'Failed to reinstate', { title: 'Error', variant: 'danger' });
      }
    } catch (e) {
      await showAlert('Network error', { title: 'Error', variant: 'danger' });
    }
    setReinstating(null);
  };

  const handleDeleteOccurrence = async (occ) => {
    const ok = await confirm(`Delete the ${formatDate(occ.date)} occurrence?`, {
      title: 'Delete Occurrence',
      confirmText: 'Delete',
      variant: 'danger',
      details: [
        `${formatCurrency(occ.amount)} will be reversed from the account`,
        'You can reinstate this occurrence later',
      ],
    });
    if (!ok) return;
    try {
      await fetch(`/api/transactions/${occ.transactionId}`, { method: 'DELETE' });
      await openOccurrences(occRule);
      invalidateCache('/api/recurring');
      invalidateCache('/api/transactions');
      invalidateCache('/api/accounts');
      refreshRules();
    } catch (e) {
      console.error(e);
    }
  };

  return (
    <Page
      title="Recurring"
      actions={<Button onClick={openCreate} id="add-rule-btn">Add recurring</Button>}
    >
      <Section title="Rules" aside={<span className="hidden sm:inline">Click a rule to see its occurrences</span>} bodyClassName="py-0">
        {loading ? (
          <div className="space-y-2 py-4">
            {[1, 2, 3].map(i => <Skeleton key={i} className="h-10" />)}
          </div>
        ) : rules.length > 0 ? (
          <Table>
            <thead>
              <tr>
                <Th>Name</Th>
                <Th className="hidden md:table-cell">Category</Th>
                <Th className="hidden lg:table-cell">Account</Th>
                <Th className="hidden sm:table-cell">Schedule</Th>
                <Th align="right">Amount</Th>
                <Th align="right"><span className="sr-only">Actions</span></Th>
              </tr>
            </thead>
            <tbody>
              {rules.map((rule) => {
                const isEnded = rule.endDate && toDateStringMT(rule.endDate) < getTodayMT();
                const isDimmed = rule.isActive === false || isEnded;
                return (
                  <tr key={rule._id} className={`${rowClass} ${isDimmed ? 'opacity-50' : ''}`}>
                    <Td>
                      <button
                        type="button"
                        onClick={() => openOccurrences(rule)}
                        className="cursor-pointer text-left text-ink underline-offset-4 hover:underline"
                      >
                        {rule.name}
                      </button>
                      <span className="ml-2 inline-flex gap-1 align-middle">
                        {isEnded && <Tag>ended</Tag>}
                        {rule.isActive === false && !isEnded && <Tag tone="warn">paused</Tag>}
                      </span>
                      <div className="mt-0.5 text-xs text-faint md:hidden">{rule.category} · {freqLabel[rule.frequency]}</div>
                    </Td>
                    <Td className="hidden text-muted md:table-cell">{rule.category}</Td>
                    <Td className="hidden text-muted lg:table-cell">{getAccountName(rule.accountId)}</Td>
                    <Td className="hidden text-xs text-muted sm:table-cell">
                      <div className="text-ink/90">{freqLabel[rule.frequency]}</div>
                      <div className="text-faint">
                        since {formatDate(rule.startDate)}
                        {rule.endDate ? ` · ${isEnded ? 'ended' : 'until'} ${formatDate(rule.endDate)}` : ''}
                      </div>
                    </Td>
                    <Td align="right">
                      <span className={`num ${rule.type === 'income' ? 'text-accent' : 'text-debit'}`}>
                        {rule.type === 'income' ? '+' : '-'}{formatCurrency(rule.amount)}
                      </span>
                    </Td>
                    <Td align="right" className="whitespace-nowrap">
                      <span className="inline-flex gap-3">
                        <TextButton
                          className="text-xs"
                          onClick={() => toggleActive(rule)}
                          title={isEnded ? 'Rule has ended' : rule.isActive === false ? 'Enable' : 'Disable'}
                        >
                          {isEnded ? 'ended' : rule.isActive === false ? 'resume' : 'pause'}
                        </TextButton>
                        <TextButton tone="warn" className="text-xs" onClick={() => handleUndo(rule)} title="Undo all generated transactions">undo</TextButton>
                        <TextButton className="text-xs" onClick={() => openEdit(rule)}>edit</TextButton>
                        <TextButton tone="debit" className="text-xs" onClick={() => handleDelete(rule)}>delete</TextButton>
                      </span>
                    </Td>
                  </tr>
                );
              })}
            </tbody>
          </Table>
        ) : (
          <div className="py-10 text-center">
            <p className="mb-1 text-ink">No recurring items</p>
            <p className="mb-5 text-sm text-muted">Add recurring items to project your future balances.</p>
            <Button onClick={openCreate}>Add your first recurring item</Button>
          </div>
        )}
      </Section>

      <Modal isOpen={showModal} onClose={() => setShowModal(false)} title={editingRule ? 'Edit recurring item' : 'New recurring item'}>
        <form onSubmit={handleSave}>
          <div className="flex flex-col gap-4">
            <Field label="Rule name">
              <Input placeholder="e.g. Monthly Rent" value={form.name} onChange={(e) => setForm({...form, name: e.target.value})} required />
            </Field>
            <div className="grid grid-cols-2 gap-4">
              <Field label="Amount">
                <Input className="num" type="number" step="0.01" min="0.01" placeholder="0.00" value={form.amount} onChange={(e) => setForm({...form, amount: e.target.value})} required />
              </Field>
              <Field label="Type">
                <Select value={form.type} onChange={(e) => setForm({...form, type: e.target.value, category: e.target.value === 'income' ? 'Work' : 'Misc'})}>
                  <option value="expense">Expense</option>
                  <option value="income">Income</option>
                </Select>
              </Field>
            </div>
            <div className="grid grid-cols-2 gap-4">
              <Field label="Frequency">
                <Select value={form.frequency} onChange={(e) => setForm({...form, frequency: e.target.value})}>
                  {RULE_FREQUENCIES.map(f => <option key={f} value={f}>{freqLabel[f]}</option>)}
                </Select>
              </Field>
              <div>
                <span className="mb-1.5 block text-xs text-muted">Category</span>
                <CategoryPicker
                  categories={categories}
                  value={form.category}
                  onChange={cat => setForm({...form, category: cat})}
                />
              </div>
            </div>
            <div className="grid grid-cols-2 gap-4">
              <Field label="Start date">
                <Input type="date" value={form.startDate} onChange={(e) => setForm({...form, startDate: e.target.value})} required />
              </Field>
              <Field label="End date (optional)">
                <Input type="date" value={form.endDate} onChange={(e) => setForm({...form, endDate: e.target.value})} />
              </Field>
            </div>
            <Field label="Account">
              <Select value={form.accountId} onChange={(e) => setForm({...form, accountId: e.target.value})}>
                <option value="">No specific account</option>
                {accounts.map(a => <option key={a._id} value={a._id}>{a.name}</option>)}
              </Select>
            </Field>
          </div>
          <div className="mt-6 flex justify-end gap-3">
            <Button type="button" variant="secondary" onClick={() => setShowModal(false)}>Cancel</Button>
            <Button type="submit" disabled={saving}>
              {saving ? 'Saving…' : editingRule ? 'Update' : 'Create'}
            </Button>
          </div>
        </form>
      </Modal>

      {/* ─── Occurrence Detail Modal ──────────────── */}
      <Modal isOpen={showOccurrences} onClose={() => setShowOccurrences(false)} title={occRule ? `${occRule.name} — Occurrences` : 'Occurrences'}>
        {occLoading ? (
          <div className="flex flex-col gap-2">
            {[1, 2, 3, 4].map(i => <Skeleton key={i} className="h-10" />)}
          </div>
        ) : (
          <>
            {/* Summary */}
            <div className="mb-4 grid grid-cols-3 divide-x divide-rule border-y border-rule">
              <div className="px-3 py-2">
                <p className="text-[11px] text-faint">Total</p>
                <p className="num text-lg text-ink">{occSummary.total}</p>
              </div>
              <div className="px-3 py-2">
                <p className="text-[11px] text-faint">Active</p>
                <p className="num text-lg text-accent">{occSummary.active}</p>
              </div>
              <div className="px-3 py-2">
                <p className="text-[11px] text-faint">Missing</p>
                <p className={`num text-lg ${occSummary.missing > 0 ? 'text-debit' : 'text-muted'}`}>{occSummary.missing}</p>
              </div>
            </div>

            {/* Occurrence list */}
            <div className="max-h-[400px] overflow-y-auto">
              {occurrences.length === 0 ? (
                <Empty>No occurrences to show</Empty>
              ) : (
                occurrences.map((occ, i) => (
                  <div
                    key={occ.date + i}
                    className={`flex items-center justify-between gap-3 border-b border-rule px-1 py-2.5 ${occ.active ? '' : 'opacity-60'}`}
                  >
                    <div className="min-w-0">
                      <p className={`num text-sm ${occ.active ? 'text-ink' : 'text-muted'}`}>{formatDate(occ.date)}</p>
                      <p className="text-xs text-faint">
                        {occ.active ? 'Active' : 'Missing — deleted or not yet processed'}
                        {occ.orphan && ' (date shifted from rule edit)'}
                      </p>
                    </div>
                    <div className="flex shrink-0 items-center gap-4">
                      <span className={`num text-sm ${occ.active ? (occRule?.type === 'income' ? 'text-accent' : 'text-debit') : 'text-muted'}`}>
                        {occRule?.type === 'income' ? '+' : '-'}{formatCurrency(occ.amount)}
                      </span>
                      {occ.active ? (
                        <TextButton
                          tone="debit"
                          className="text-xs"
                          onClick={(e) => { e.stopPropagation(); handleDeleteOccurrence(occ); }}
                        >
                          delete
                        </TextButton>
                      ) : (
                        <TextButton
                          tone="accent"
                          className="text-xs"
                          onClick={(e) => { e.stopPropagation(); handleReinstate(occ); }}
                          disabled={reinstating === occ.date}
                        >
                          {reinstating === occ.date ? 'reinstating…' : 'reinstate'}
                        </TextButton>
                      )}
                    </div>
                  </div>
                ))
              )}
            </div>

            <div className="mt-5 flex justify-end">
              <Button variant="secondary" onClick={() => { setShowOccurrences(false); refreshRules(); }}>Close</Button>
            </div>
          </>
        )}
      </Modal>
    </Page>
  );
}

export default function RecurringPage() {
  return (
    <AuthGuard>
      <Sidebar />
      <RecurringContent />
    </AuthGuard>
  );
}
